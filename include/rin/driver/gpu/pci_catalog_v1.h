#ifndef RIN_DRIVER_GPU_PCI_CATALOG_V1_H
#define RIN_DRIVER_GPU_PCI_CATALOG_V1_H

#include <stdint.h>

#define RIN_GPU_PCI_PROFILE_VERSION UINT32_C(0x00010000)
#define RIN_GPU_PCI_MAX_MSIX_VECTORS 64u
#define RIN_GPU_PCI_VENDOR_INTEL UINT16_C(0x8086)
#define RIN_GPU_PCI_VENDOR_AMD UINT16_C(0x1002)
#define RIN_GPU_PCI_VENDOR_NVIDIA UINT16_C(0x10de)
#define RIN_GPU_PCI_INTEL_XE_LPG_DEVICE UINT16_C(0x7d55)
#define RIN_GPU_PCI_INTEL_MTL_M_DEVICE UINT16_C(0x7d40)
#define RIN_GPU_PCI_INTEL_MTL_U_DEVICE UINT16_C(0x7d45)
#define RIN_GPU_PCI_INTEL_MTL_P_DEVICE UINT16_C(0x7d55)
#define RIN_GPU_PCI_INTEL_MTL_H_DEVICE UINT16_C(0x7d60)
#define RIN_GPU_PCI_INTEL_MTL_DEVICE_7DD5 UINT16_C(0x7dd5)
#define RIN_GPU_PCI_INTEL_XE_LPG_SUBSYSTEM_VENDOR UINT16_C(0x1028)
#define RIN_GPU_PCI_INTEL_XE_LPG_SUBSYSTEM_DEVICE UINT16_C(0x0c63)
#define RIN_GPU_PCI_AMD_RDNA3_DEVICE UINT16_C(0x744c)
#define RIN_GPU_PCI_AMD_RDNA3_SUBSYSTEM_VENDOR UINT16_C(0x1eae)
#define RIN_GPU_PCI_AMD_RDNA3_SUBSYSTEM_DEVICE UINT16_C(0x790a)
#define RIN_GPU_PCI_NVIDIA_ADA_DEVICE UINT16_C(0x2684)
#define RIN_GPU_PCI_FAMILY_INTEL_XE_LPG UINT32_C(1)
#define RIN_GPU_PCI_FAMILY_AMD_RDNA3 UINT32_C(2)
#define RIN_GPU_PCI_FAMILY_NVIDIA_ADA UINT32_C(3)

/* Subsystem IDs identify the OEM board. Intel MTL integrated graphics are
 * admitted by device ID, with graphics/media IP discovery performed later. */
static inline int rin_gpu_pci_intel_mtl_device_id_valid(uint16_t device_id)
{
    return device_id == RIN_GPU_PCI_INTEL_MTL_M_DEVICE ||
           device_id == RIN_GPU_PCI_INTEL_MTL_U_DEVICE ||
           device_id == RIN_GPU_PCI_INTEL_MTL_P_DEVICE ||
           device_id == RIN_GPU_PCI_INTEL_MTL_H_DEVICE ||
           device_id == RIN_GPU_PCI_INTEL_MTL_DEVICE_7DD5;
}

#endif /* RIN_DRIVER_GPU_PCI_CATALOG_V1_H */
