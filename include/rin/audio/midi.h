/* Fixed UMP ABI for privacy-gated MIDI I/O. */

#ifndef RIN_API_RIN_MIDI_H
#define RIN_API_RIN_MIDI_H

#include <stdint.h>

#define RIN_MIDI_PACKET_VERSION UINT32_C(0x00010000)

#define RIN_MIDI_COMMAND_RECEIVE_UMP UINT32_C(1)
#define RIN_MIDI_COMMAND_SEND_UMP UINT32_C(2)

#define RIN_MIDI_PACKET_TIMESTAMP_VALID UINT32_C(0x00000001)
#define RIN_MIDI_PACKET_KNOWN_FLAGS RIN_MIDI_PACKET_TIMESTAMP_VALID

/* This V1 boundary accepts Utility, System, MIDI 1.0/2.0 Channel Voice,
 * SysEx7, SysEx8, Mixed Data Set, Flex Data and UMP Stream message types. */
#define RIN_MIDI_UMP_TYPE_UTILITY UINT32_C(0x0)
#define RIN_MIDI_UMP_TYPE_SYSTEM UINT32_C(0x1)
#define RIN_MIDI_UMP_TYPE_MIDI1_CHANNEL_VOICE UINT32_C(0x2)
#define RIN_MIDI_UMP_TYPE_DATA64 UINT32_C(0x3)
#define RIN_MIDI_UMP_TYPE_MIDI2_CHANNEL_VOICE UINT32_C(0x4)
#define RIN_MIDI_UMP_TYPE_DATA128 UINT32_C(0x5)
#define RIN_MIDI_UMP_TYPE_FLEX_DATA UINT32_C(0xd)
#define RIN_MIDI_UMP_TYPE_STREAM UINT32_C(0xf)

#define RIN_MIDI_UMP_UTILITY_NOOP UINT32_C(0)
#define RIN_MIDI_UMP_UTILITY_JR_CLOCK UINT32_C(1)
#define RIN_MIDI_UMP_UTILITY_JR_TIMESTAMP UINT32_C(2)
#define RIN_MIDI_UMP_UTILITY_DELTA_CLOCKSTAMP_TPQ UINT32_C(3)
#define RIN_MIDI_UMP_UTILITY_DELTA_CLOCKSTAMP UINT32_C(4)

#define RIN_MIDI_UMP_SYSEX_COMPLETE UINT32_C(0)
#define RIN_MIDI_UMP_SYSEX_START UINT32_C(1)
#define RIN_MIDI_UMP_SYSEX_CONTINUE UINT32_C(2)
#define RIN_MIDI_UMP_SYSEX_END UINT32_C(3)

#define RIN_MIDI_UMP_MDS_HEADER UINT32_C(8)
#define RIN_MIDI_UMP_MDS_PAYLOAD UINT32_C(9)

#define RIN_MIDI_UMP_FORMAT_COMPLETE UINT32_C(0)
#define RIN_MIDI_UMP_FORMAT_START UINT32_C(1)
#define RIN_MIDI_UMP_FORMAT_CONTINUE UINT32_C(2)
#define RIN_MIDI_UMP_FORMAT_END UINT32_C(3)

#define RIN_MIDI_UMP_FLEX_ADDRESS_CHANNEL UINT32_C(0)
#define RIN_MIDI_UMP_FLEX_ADDRESS_GROUP UINT32_C(1)

#define RIN_MIDI_UMP_FLEX_BANK_SETUP UINT32_C(0)
#define RIN_MIDI_UMP_FLEX_BANK_METADATA_TEXT UINT32_C(1)
#define RIN_MIDI_UMP_FLEX_BANK_PERFORMANCE_TEXT UINT32_C(2)

#define RIN_MIDI_UMP_FLEX_SETUP_SET_TEMPO UINT32_C(0x00)
#define RIN_MIDI_UMP_FLEX_SETUP_SET_TIME_SIGNATURE UINT32_C(0x01)
#define RIN_MIDI_UMP_FLEX_SETUP_SET_METRONOME UINT32_C(0x02)
#define RIN_MIDI_UMP_FLEX_SETUP_SET_KEY_SIGNATURE UINT32_C(0x05)
#define RIN_MIDI_UMP_FLEX_SETUP_SET_CHORD_NAME UINT32_C(0x06)

#define RIN_MIDI_UMP_STREAM_ENDPOINT_DISCOVERY UINT32_C(0x000)
#define RIN_MIDI_UMP_STREAM_ENDPOINT_INFO UINT32_C(0x001)
#define RIN_MIDI_UMP_STREAM_DEVICE_IDENTITY UINT32_C(0x002)
#define RIN_MIDI_UMP_STREAM_ENDPOINT_NAME UINT32_C(0x003)
#define RIN_MIDI_UMP_STREAM_PRODUCT_INSTANCE_ID UINT32_C(0x004)
#define RIN_MIDI_UMP_STREAM_CONFIGURATION_REQUEST UINT32_C(0x005)
#define RIN_MIDI_UMP_STREAM_CONFIGURATION_NOTIFICATION UINT32_C(0x006)
#define RIN_MIDI_UMP_STREAM_FUNCTION_BLOCK_DISCOVERY UINT32_C(0x010)
#define RIN_MIDI_UMP_STREAM_FUNCTION_BLOCK_INFO UINT32_C(0x011)
#define RIN_MIDI_UMP_STREAM_FUNCTION_BLOCK_NAME UINT32_C(0x012)
#define RIN_MIDI_UMP_STREAM_START_OF_CLIP UINT32_C(0x020)
#define RIN_MIDI_UMP_STREAM_END_OF_CLIP UINT32_C(0x021)

#define RIN_MIDI_STREAM_PROTOCOL_MIDI1 UINT32_C(0x01)
#define RIN_MIDI_STREAM_PROTOCOL_MIDI2 UINT32_C(0x02)
#define RIN_MIDI_STREAM_CONFIG_RX_JR UINT32_C(0x01)
#define RIN_MIDI_STREAM_CONFIG_TX_JR UINT32_C(0x02)
#define RIN_MIDI_STREAM_CONFIG_KNOWN_FLAGS \
    (RIN_MIDI_STREAM_CONFIG_RX_JR | RIN_MIDI_STREAM_CONFIG_TX_JR)

typedef struct RinMidiPacketV1 {
    uint32_t struct_size;
    uint32_t version;
    uint64_t monotonic_time_ns;
    uint32_t words[4];
    uint32_t word_count;
    uint32_t flags;
} RinMidiPacketV1;

#if defined(__cplusplus)
static_assert(sizeof(RinMidiPacketV1) == 40u,
              "RinMidiPacketV1 ABI size changed");
#else
_Static_assert(sizeof(RinMidiPacketV1) == 40u,
               "RinMidiPacketV1 ABI size changed");
#endif

#endif /* RIN_API_RIN_MIDI_H */
